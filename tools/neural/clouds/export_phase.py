"""Export the tabulated Lorenz-Mie phase functions (mie.py) for the runtime: src/neural/cloud-mie-weights.js.

    $VENV tools/neural/clouds/export_phase.py

Per effective radius (6, 10, 16 um) and colour band (R, G, B): p(theta) in sr^-1 at NU texels of the coordinate
    u(theta) = 0.5 + tan(C (theta - pi/2)) / (2 tan(C pi / 2)),  C = 0.9
which puts ~40x more texels near 0 deg (diffraction peak, corona) and 180 deg (glory) than at the side; the fogbow at
~141 deg gets 0.75 deg per texel. Float32, base64. Also g, f(theta_c) and the truncated-peak data the shader needs.
"""
import base64
import json
import math
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pt  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
NU = 512
C = 0.9
REFFS = [6.0, 10.0, 16.0]


def theta_of_u(u):
    return math.pi / 2 + np.arctan((u - 0.5) * 2 * math.tan(C * math.pi / 2)) / C


def main():
    z = np.load(os.path.join(pt.DATA, 'mie_tables.npz'))
    th = z['theta']
    u = (np.arange(NU) + 0.5) / NU        # texel centres (the shader samples u * (NU-1)/NU + 0.5/NU style: see JS)
    u = np.linspace(0, 1, NU)             # node values at u = i / (NU - 1)
    tu = theta_of_u(u)
    tables, meta = [], []
    for re in REFFS:
        i = int(np.argmin(np.abs(z['reff'] - re)))
        for j in range(3):
            tables.append(np.interp(tu, th, z['P'][i, j]))
        ph = pt.Phase(re, 'G', 4.0)
        meta.append(dict(reff=re, g=[float(v) for v in z['g'][i]], albedo=[float(v) for v in z['albedo'][i]],
                         qext=[float(v) for v in z['qext'][i]], f=ph.f, thetaC=4.0, gTrunc=ph.g_trunc, pC=ph.pc, aurV=ph.aur_v))
    arr = np.stack(tables).astype(np.float32)          # [reff*3 + band][NU]
    # accuracy of the u-grid representation (linear interpolation in u) vs the full table, energy-weighted
    errs = []
    for k in range(arr.shape[0]):
        re_i, b = divmod(k, 3)
        i = int(np.argmin(np.abs(z['reff'] - REFFS[re_i])))
        uu = 0.5 + np.tan(C * (th - math.pi / 2)) / (2 * math.tan(C * math.pi / 2))
        rec = np.interp(uu, u, arr[k])
        errs.append(float(np.max(np.abs(np.log(rec / z['P'][i, b])))))
    out = dict(nu=NU, c=C, reffs=REFFS, bands=['R', 'G', 'B'], meta=meta,
               b64=base64.b64encode(arr.tobytes()).decode(), maxLnErrU=max(errs),
               source='tools/neural/clouds/mie.py: Bohren-Huffman Mie, Hale-Querry water, modified gamma v_eff 0.1, '
                      'band averages R 600-680 / G 500-570 / B 430-490 nm')
    js = ('// Generated by tools/neural/clouds/export_phase.py: tabulated Lorenz-Mie phase functions of cloud droplet\n'
          '// populations (see src/neural/cloud-ms.js, cloudPhaseMie). Do not edit.\n'
          'export const CLOUD_MIE_TABLES = ' + json.dumps(out, indent=1) + ';\n')
    open(os.path.join(ROOT, 'src', 'neural', 'cloud-mie-weights.js'), 'w').write(js)
    print('max |ln p| error of the u-grid:', max(errs), ' size', len(js))


if __name__ == '__main__':
    main()
