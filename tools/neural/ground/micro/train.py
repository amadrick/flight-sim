"""Train the micro-relief transfer network on sim.py's dataset and compare it with the analytic baselines.
   python3 train.py micro_dataset.npz ../../../../src/neural/ground-micro-weights.js
Network: 4 inputs (cos_s, cos_v, cos_phi, RMS slope) -> 20 tanh -> 20 tanh -> 1 (R = K cos_s, the radiance toward the
viewer per unit of normal-incidence flat-Lambertian radiance). Baselines: Lambert (K = 1) and Oren-Nayar with the
roughness angle fitted to the same training data (sigma = a * atan(slope), one global a)."""
import numpy as np, sys, json, base64, time

d = np.load(sys.argv[1]); tr, te = d['train'], d['test']
def feats(a): return np.stack([a[:, 0] * 2 - 1, a[:, 1] * 2 - 1, a[:, 2], a[:, 3] * 2 - 1], 1).astype(np.float64)
Xtr, ytr, Xte, yte = feats(tr), tr[:, 4].astype(np.float64), feats(te), te[:, 4].astype(np.float64)

def oren_nayar(a, k):
    cs, cv, cphi, s = a[:, 0], a[:, 1], a[:, 2], a[:, 3]
    sg = k * np.arctan(s); s2 = sg * sg
    A = 1 - 0.5 * s2 / (s2 + 0.33); B = 0.45 * s2 / (s2 + 0.09)
    ti, tv = np.arccos(np.clip(cs, 0, 1)), np.arccos(np.clip(cv, 0, 1))
    al, be = np.maximum(ti, tv), np.minimum(ti, tv)
    return cs * (A + B * np.maximum(cphi, 0) * np.sin(al) * np.tan(be))
ks = np.linspace(0.2, 2.5, 116)
k_on = ks[np.argmin([np.mean((oren_nayar(tr, k) - ytr) ** 2) for k in ks])]

rng = np.random.default_rng(1)
sizes = [4, 20, 20, 1]
W = [rng.normal(0, 1 / np.sqrt(sizes[i]), (sizes[i + 1], sizes[i])) for i in range(3)]
b = [np.zeros(sizes[i + 1]) for i in range(3)]
def fwd(X, W, b):
    a1 = np.tanh(X @ W[0].T + b[0]); a2 = np.tanh(a1 @ W[1].T + b[1])
    return (a2 @ W[2].T + b[2])[:, 0], a1, a2
P = W + b; m = [np.zeros_like(p) for p in P]; v = [np.zeros_like(p) for p in P]
t0 = time.time()
for it in range(1, 6001):
    idx = rng.integers(0, len(Xtr), 4096); X, y = Xtr[idx], ytr[idx]
    out, a1, a2 = fwd(X, W, b)
    g = 2 * (out - y)[:, None] / len(y)
    gW2 = g.T @ a2; gb2 = g.sum(0); d2 = (g @ W[2]) * (1 - a2 * a2)
    gW1 = d2.T @ a1; gb1 = d2.sum(0); d1 = (d2 @ W[1]) * (1 - a1 * a1)
    gW0 = d1.T @ X; gb0 = d1.sum(0)
    lr = 4e-3 * (0.5 ** (it / 1800))
    for i, gp in enumerate([gW0, gW1, gW2, gb0, gb1, gb2]):
        m[i] = 0.9 * m[i] + 0.1 * gp; v[i] = 0.999 * v[i] + 0.001 * gp * gp
        P[i] -= lr * (m[i] / (1 - 0.9 ** it)) / (np.sqrt(v[i] / (1 - 0.999 ** it)) + 1e-8)
W, b = P[:3], P[3:]

def report(name, pred, y, a):
    e = pred - y
    rel = np.abs(e) / (y + 0.02)
    graz = (a[:, 0] < 0.25) | (a[:, 1] < 0.3)
    rough = a[:, 3] > 0.5
    return dict(model=name, rmse=float(np.sqrt(np.mean(e * e))), mean_rel=float(np.mean(rel)), p95_rel=float(np.percentile(rel, 95)),
                rmse_grazing=float(np.sqrt(np.mean(e[graz] ** 2))), rmse_rough=float(np.sqrt(np.mean(e[rough] ** 2))))
res = [report('lambert', te[:, 0].astype(np.float64), yte, te), report(f'oren-nayar(sigma={k_on:.2f}*atan(s))', oren_nayar(te, k_on), yte, te),
       report('mlp 4-20-20-1', fwd(Xte, W, b)[0], yte, te), report('mlp (train set)', fwd(Xtr, W, b)[0], ytr, tr)]
for r in res: print(json.dumps(r))
flat = np.concatenate([np.concatenate([W[i].ravel(), b[i]]) for i in range(3)]).astype(np.float32)
js = f"""// GENERATED by tools/neural/ground/micro/train.py - do not edit. Micro-relief transfer network (see ground-micro.js).
export const GROUND_MICRO_MODEL = {{
  sizes: {sizes}, params: {len(flat)}, orenNayarK: {k_on:.3f},
  eval: {json.dumps(res)},
  b64: '{base64.b64encode(flat.tobytes()).decode()}',
}};
"""
open(sys.argv[2], 'w').write(js)
# test vectors for the JS twin
iv = rng.integers(0, len(Xte), 24)
json.dump({'x': te[iv, :4].tolist(), 'y': fwd(Xte[iv], W, b)[0].tolist()}, open(sys.argv[2].replace('-weights.js', '-test-vectors.json'), 'w'))
print(f'trained in {time.time() - t0:.0f} s, {len(flat)} parameters')
