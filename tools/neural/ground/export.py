"""Export the trained ground-cover network for the browser.

    python3 export.py [data/model.npz]   ->  src/neural/ground-weights.js, src/neural/ground-test-vectors.json

The weights are rounded to float32 and embedded as base64; the test vectors are evaluated in float64 with those
rounded weights (the arithmetic of src/neural/ground-cover.js), from raw clipmap features of real training samples.
"""
import base64, datetime, glob, json, os, sys
import numpy as np
import features as F
import ecosim

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, 'data')
OUT = os.path.normpath(os.path.join(HERE, '..', '..', '..', 'src', 'neural'))


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(DATA, 'model.npz')
    d = np.load(path)
    sizes = [int(v) for v in d['sizes']]
    layers = [(d[f'w{i}'].astype(np.float32), d[f'b{i}'].astype(np.float32)) for i in range(len(sizes) - 1)]
    flat = np.concatenate([np.concatenate([w.ravel(), b.ravel()]) for w, b in layers]).astype('<f4')
    # generalisation numbers come from the run that held whole patches out (train.py without --all), if present
    hold = os.path.join(DATA, 'model_holdout.json')
    report = json.load(open(hold if os.path.exists(hold) else path.replace('.npz', '.json')))

    def forward(x):
        for i, (w, b) in enumerate(layers):
            x = x @ w.astype(np.float64).T + b.astype(np.float64)
            x = np.tanh(x) if i < len(layers) - 1 else 1.0 / (1.0 + np.exp(-x))
        return x

    rng = np.random.default_rng(3)
    vecs = []
    files = sorted(glob.glob(os.path.join(DATA, 'ds_*.npz')))
    for f in files[::3]:
        ds = np.load(f)
        for k in rng.choice(len(ds['lv']), 6, replace=False):
            kb = float(rng.random()) if rng.random() < 0.5 else 0.0
            raw = (ds['rawA'][k] * (1 - kb) + ds['rawB'][k] * kb).astype(np.float64)
            lod = float(ds['lv'][k]) + kb
            latk = float(ds['latk'][k])
            x = F.inputs(raw, lod, latk)
            vecs.append({'raw': [float(v) for v in raw], 'lod': lod, 'latK': latk, 'x': [float(v) for v in x], 'y': [float(v) for v in forward(x)]})
    json.dump({'outputs': ecosim.OUT_NAMES, 'vectors': vecs}, open(os.path.join(OUT, 'ground-test-vectors.json'), 'w'))

    meta = {
        'sizes': sizes, 'params': int(flat.size), 'activation': 'tanh', 'output': 'logistic', 'outputs': ecosim.OUT_NAMES,
        'trained': datetime.date.today().isoformat(),
        'fit': {k: {'rmse_val': round(v['rmse_val'], 4), 'r2_val': round(v['r2_val'], 3), 'rmse_train': round(v['rmse_train'], 4)} for k, v in report['outputs'].items()},
        'fit_note': 'rmse_val / r2_val: 7 whole terrain patches held out of training (unseen terrain); the shipped weights are then refit on all 48 patches',
        'train_samples': report['train_samples'], 'val_samples': report['val_samples'],
    }
    b64 = base64.b64encode(flat.tobytes()).decode()
    js = ('// GENERATED by tools/neural/ground/export.py - do not edit.\n'
          '// Ground-cover network: terrain features -> simulated ecosystem cover (see ground-cover.js).\n'
          'export const GROUND_COVER_MODEL = ' + json.dumps({**meta, 'b64': b64}, indent=1) + ';\n')
    open(os.path.join(OUT, 'ground-weights.js'), 'w').write(js)
    print('wrote ground-weights.js (%d params, %d bytes base64), %d test vectors' % (flat.size, len(b64), len(vecs)))


if __name__ == '__main__':
    main()
