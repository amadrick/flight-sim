"""Export the trained networks (results/nets/*.npz) as the JS weight module and the JS/Python test vectors.

    python3 tools/neural/aero/export.py

Writes src/neural/aero-weights.js and src/neural/test-vectors-aero.json.
"""
import base64
import json
import os
import numpy as np

import aircraft as AC
import planforms
import train as T

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.normpath(os.path.join(HERE, '..', '..', '..', 'src', 'neural'))


def main():
    rng = np.random.default_rng(11)
    lines = ['// Generated by tools/neural/aero/export.py: do not edit. Per-aircraft aerodynamic correction networks',
             '// (int16-quantised weights, little endian, base64; s = scale per head, b = output bounds, v = valid flags,',
             '// f = outputs whose correction fades out with flap extension).',
             'export const AERO_NETS = {',
             f'  hidden: {T.H},', f'  heads: {json.dumps([[n, k] for n, k in T.HEADS])},', f'  gate: [{T.G0}, {T.G1}],', f'  fade: [{T.FADE0}, {T.FADE1}],', '  aircraft: {']
    vec = dict(heads=[n for n, _ in T.HEADS], aircraft={})
    total = 0
    for aid in planforms.IDS:
        path = os.path.join(T.NETS, f'{aid}.npz')
        if not os.path.exists(path):
            continue
        N = np.load(path)
        ac = AC.load_aircraft(aid)
        q = np.concatenate([N[f'{n}_q'] for n, _ in T.HEADS]).astype('<i2')
        s = [float(N[f'{n}_s']) for n, _ in T.HEADS]
        b = [float(f'{x:.6g}') for n, _ in T.HEADS for x in N[f'{n}_bound']]
        v = [int(x) for n, _ in T.HEADS for x in N[f'{n}_valid']]
        ff = [int(x) for n, _ in T.HEADS for x in N[f'{n}_ff']]
        hb = float(f"{float(N['g_hbmin']):.5g}")
        total += len(q)
        lines.append(f"    {aid}: {{ flap: {1 if ac.has_flap else 0}, hbMin: {hb}, s: {json.dumps(s)}, b: {json.dumps(b)}, v: {json.dumps(v)}, f: {json.dumps(ff)},")
        lines.append(f"      w: '{base64.b64encode(q.tobytes()).decode()}' }},")
        # test vectors: random inputs inside and outside the trained ranges, evaluated with the quantised weights
        xs, ys = [], []
        for k, (n, n_out) in enumerate(T.HEADS):
            th = T.dequantise(N[f'{n}_q'], N[f'{n}_s'])
            X = np.stack([rng.uniform(-2.0, 3.5, 6), rng.uniform(-0.2, 1.2, 6), rng.uniform(0.0, 1.0, 6), rng.uniform(-1.2, 1.2, 6)], 1)
            if n == 'g':
                X[:, 0] = rng.uniform(-3.5, 0.6, 6)
            Y = T.forward(th, X, np.array([float(x) for x in b[sum(c for _, c in T.HEADS[:k]):][:n_out]]))
            Y = Y * N[f'{n}_valid'][None]
            for x, y in zip(X, Y):
                xs.append([k] + [float(t) for t in x]); ys.append([float(t) for t in y])
        vec['aircraft'][aid] = dict(x=xs, y=ys)
    lines += ['  },', '};', '']
    with open(os.path.join(SRC, 'aero-weights.js'), 'w') as f:
        f.write('\n'.join(lines))
    with open(os.path.join(SRC, 'test-vectors-aero.json'), 'w') as f:
        json.dump(vec, f)
    print(f'{len(vec["aircraft"])} aircraft, {total} weights, {os.path.getsize(os.path.join(SRC, "aero-weights.js")) / 1024:.0f} kB')


if __name__ == '__main__':
    main()
