"""Export the trained atmosphere networks to src/neural/atmo-weights.js and test vectors to
src/neural/atmo-test-vectors.json (the JS forward pass must reproduce these).

  python3 export.py        (after train_sun.py and train_sky.py)
"""
import base64
import datetime
import json
import math
import os
import sys
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C
import classic as K
import train_sky as TS

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, '..', '..', '..', 'src', 'neural'))

# Where the sky correction applies (degrees of sun elevation). Full strength from the start of astronomical night
# fading in (nightTo -> nightFrom) up to dayFrom, then eased to `day` at dayTo and above.
SKY_BLEND = dict(nightTo=-11.0, nightFrom=-7.0, dayFrom=float(os.environ.get('DAY_FROM', 20)),
                 dayTo=float(os.environ.get('DAY_TO', 45)), day=float(os.environ.get('DAY_W', 1.0)))


def load_net(path):
    d = np.load(path, allow_pickle=False)
    flat = d['flat'].astype('<f4')
    sizes = [int(s) for s in d['sizes']]
    layers, p = [], 0
    f64 = flat.astype(np.float64)
    for i in range(len(sizes) - 1):
        a, o = sizes[i], sizes[i + 1]
        W = f64[p:p + a * o].reshape(o, a)
        p += a * o
        b = f64[p:p + o]
        p += o
        layers.append((W, b))
    assert p == len(flat)
    return d, flat, sizes, layers


def fwd(layers, x):
    for i, (W, b) in enumerate(layers):
        x = x @ W.T + b
        if i < len(layers) - 1:
            x = x / np.sqrt(1 + x * x)
    return x


def sky_norm(sky_layers):
    """Irradiance-weighted mean of the network ratio over the sky at noon (sun 45..75 deg, sea level, typical haze):
    the reference is divided by it so the tuned noon exposure / white balance does not move."""
    rng = np.random.default_rng(11)
    n = 2048
    u = (np.arange(n) + rng.random(n)) / n
    phi = rng.random(n) * 2 * math.pi
    ct = np.sqrt(1 - u)
    el = np.arcsin(ct)
    num = np.zeros(3)
    den = np.zeros(3)
    for mie in (0.025, 0.04, 0.055):
        cl = K.Classic(mie)
        for sd in (45.0, 60.0, 75.0):
            sun = math.radians(sd)
            s = np.tile([math.cos(sun), math.sin(sun), 0.0], (n, 1))
            d = np.stack([np.cos(el) * np.cos(phi), np.sin(el), np.cos(el) * np.sin(phi)], 1)
            Lc = cl.sky(np.zeros(n), d, s)
            az = np.abs(np.arctan2(np.sin(phi), np.cos(phi)))
            ef = el / (math.pi / 2)
            x = TS.encode(np.full(n, sun), ef, az, np.zeros(n), np.full(n, mie), (d * s).sum(1))
            R = np.exp(fwd(sky_layers, x)[:, :3])
            num += (R * Lc).sum(0)
            den += Lc.sum(0)
    return num / den


def main():
    dsun, fsun, ssun, lsun = load_net(os.path.join(HERE, 'data', 'sun_net.npz'))
    dsky, fsky, ssky, lsky = load_net(os.path.join(HERE, 'data', 'sky_net.npz'))
    sky_meta = json.loads(str(dsky['meta']))
    norm = sky_norm(lsky)
    print('noon normalisation of the sky ratio:', norm)
    w, g = C.MIE_LOBES[0]
    cut = float(C.hg(math.cos(math.radians(C.PEAK_CUT_DEG)), g))
    model = dict(
        version=1,
        trained=datetime.date.today().isoformat(),
        sun=dict(sizes=ssun, enc=dict(drMax=float(dsun['dr_max']), doMax=float(dsun['do_max'])),
                 meta=dict(params=len(fsun), heldOutRmsLn=round(float(dsun['rms']), 4),
                           classicRmsLn=round(float(dsun['base']), 4), maxColourErr=round(float(dsun['maxerr']), 4),
                           p99ColourErr=round(float(dsun['p99']), 4), classicMaxColourErr=round(float(dsun['basemax']), 3)),
                 b64=base64.b64encode(fsun.tobytes()).decode('ascii')),
        sky=dict(sizes=ssky, enc=dict(sunLo=TS.SUN_LO, sunHi=TS.SUN_HI, altMax=TS.ALT_MAX, mieLo=TS.MIE_LO, mieHi=TS.MIE_HI),
                 meta=dict(params=len(fsky), trainSamples=sky_meta['train_samples'], testSamples=sky_meta['test_samples'],
                           heldOut={k: {kk: (round(vv, 4) if isinstance(vv, float) else vv) for kk, vv in v.items()}
                                    for k, v in sky_meta['eval'].items()}),
                 b64=base64.b64encode(fsky.tobytes()).decode('ascii')),
        peak=dict(w=w, g=g, cut=cut, cutDeg=C.PEAK_CUT_DEG),
        skyNorm=[float(v) for v in norm],
        skyBlend=SKY_BLEND,
        limb=[round(float(v), 4) for v in dsun['limb_u']],
    )
    with open(os.path.join(OUT, 'atmo-weights.js'), 'w') as f:
        f.write('// AUTO-GENERATED by tools/neural/atmo/export.py - do not edit by hand.\n'
                '// Neural air + sun networks (see src/neural/atmo.js). Weights: float32 little-endian, base64;\n'
                '// per layer W (out x in, row-major) then b; hidden activation ISRU z/sqrt(1+z^2), linear output.\n'
                'export const ATMO_MODEL = %s;\n' % json.dumps(model, indent=1))
    # ---- test vectors (float64 forward of the float32 weights = the JS arithmetic)
    rng = np.random.default_rng(21)
    DR = np.concatenate([[0, 8, 600, 300], rng.random(60) * 600])
    DO = np.concatenate([[0, 15, 700, 0], rng.random(60) * 700])
    xs = np.stack([2 * DR / float(dsun['dr_max']) - 1, 2 * DO / float(dsun['do_max']) - 1], 1)
    ysun = fwd(lsun, xs)
    m = 80
    sun = np.radians(rng.uniform(-18, 90, m))
    ef = rng.random(m)
    az = rng.random(m) * math.pi
    h = rng.random(m) * 26
    mie = np.exp(rng.uniform(math.log(0.018), math.log(0.1), m))
    cosg = np.clip(rng.uniform(-1, 1, m), -1, 1)
    ysky = fwd(lsky, TS.encode(sun, ef, az, h, mie, cosg))
    cg = np.linspace(-1, 1, 41)
    vec = dict(sun=dict(DR=DR.tolist(), DO=DO.tolist(), y=ysun.tolist()),
               sky=dict(sunEl=sun.tolist(), ef=ef.tolist(), az=az.tolist(), h=h.tolist(), mie=mie.tolist(),
                        cosg=cosg.tolist(), y=ysky.tolist()),
               peak=dict(cos=cg.tolist(), p=C.phase_peak(cg).tolist()))
    with open(os.path.join(OUT, 'atmo-test-vectors.json'), 'w') as f:
        json.dump(vec, f)
    print('wrote atmo-weights.js (sun %d + sky %d params) and atmo-test-vectors.json' % (len(fsun), len(fsky)))


if __name__ == '__main__':
    main()
