"""Export the trained flare networks for the browser: src/neural/flare-weights.js + flare-test-vectors.json.

  cd tools/neural/flare && python3 export.py
"""
import base64
import datetime
import json
import math
import os
import sys
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import features as FE                       # noqa: E402
from nn import isru                         # noqa: E402
from train import load                      # noqa: E402
from ghosts import DATA, RES, R_GRID, S_SUN, NOMINAL_FOV, LAMS as GHOST_LAMS   # noqa: E402
from diffraction import SPIKE0, BLADES      # noqa: E402
from lens import Lens                       # noqa: E402

OUT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'src', 'neural'))


def fwd(net, g, x):
    h = x
    for l, (W, b) in enumerate(zip(net.W, net.b)):
        h = h @ W[g].T + b[g]
        if l < len(net.W) - 1:
            h = isru(h)
    return h


def b64(arr):
    return base64.b64encode(np.ascontiguousarray(arr, dtype='<f4').tobytes()).decode()


def main():
    meta, ghost, star = load('meta'), load('ghost'), load('star')
    d = np.load(os.path.join(DATA, 'ghosts.npz'))
    L = Lens()
    hex_area = 0.5 * BLADES * math.sin(2 * math.pi / BLADES) / math.pi     # hexagon / circumscribed circle
    tr = {k: json.load(open(os.path.join(RES, 'train_%s.json' % k))) for k in ('meta', 'ghost', 'star')}
    consts = dict(R_MAX=FE.R_MAX, QMAX=FE.QMAX, NQA=FE.NQA, NQC=FE.NQC, NR=len(R_GRID), STAR_R0=FE.STAR_R0,
                  STAR_R1=FE.STAR_R1, STAR_S=FE.STAR_S, M_SCALE=FE.M_SCALE, SPIKE0=SPIKE0, BLADES=BLADES,
                  HEX_COMP=1.0 / hex_area, ghostNames=[str(s) for s in d['names']])
    model = dict(
        consts=consts,
        nets=dict(meta=dict(sizes=meta.sizes, b64=b64(meta.pack(0))),
                  ghost=dict(sizes=ghost.sizes, G=ghost.G, b64=b64(np.concatenate([ghost.pack(g) for g in range(ghost.G)]))),
                  star=dict(sizes=star.sizes, b64=b64(star.pack(0)))),
        meta=dict(created=datetime.date.today().isoformat(),
                  lens='Tronnier double-Gauss 50 mm f/2 (US 2,673,491; Smith, Modern Lens Design p. 312), stopped to f/%g, '
                       '%d-blade iris, single-layer MgF2 coatings' % (L.f_number, BLADES),
                  efl_mm=L.efl, frame_unit_mm=0.2 * L.efl, sun_radius_frame_units=S_SUN, nominal_fov_deg=NOMINAL_FOV,
                  wavelengths_ghost_nm=GHOST_LAMS.tolist(),
                  params=dict(meta=tr['meta']['params'], ghost=tr['ghost']['params_per_ghost'] * ghost.G, star=tr['star']['params']),
                  fit=dict(meta=tr['meta']['fit'], ghost=dict(train_rmse=tr['ghost']['fit']['train']['image_rmse_mean'],
                                                              holdout_r_rmse=tr['ghost']['fit']['holdout_r']['image_rmse_mean']),
                           star=tr['star']['fit'])))
    js = ('// Generated by tools/neural/flare/export.py - do not edit.  Neural lens-flare weights (float32, base64).\n'
          'export const FLARE_MODEL = ' + json.dumps(model, indent=1) + ';\n')
    with open(os.path.join(OUT, 'flare-weights.js'), 'w') as f:
        f.write(js)
    # test vectors (float64 arithmetic with the float32 weights == the JS forward pass)
    rng = np.random.default_rng(42)
    rs = rng.uniform(0, FE.R_MAX, 24)
    mv = np.stack([FE.meta_decode(fwd(meta, 0, FE.meta_features(r)[None])[0].reshape(-1, FE.META_OUT)) for r in rs])
    gi = rng.integers(0, ghost.G, 64)
    gr, ga, gc = rng.uniform(0, FE.R_MAX, 64), rng.uniform(-FE.QMAX, FE.QMAX, 64), rng.uniform(0, FE.QMAX, 64)
    gv = np.stack([fwd(ghost, int(g), FE.ghost_features(r, a, c)[None])[0] ** 2 for g, r, a, c in zip(gi, gr, ga, gc)])
    sr = np.exp(rng.uniform(math.log(FE.STAR_R0), math.log(FE.STAR_R1), 64))
    sp = rng.uniform(0, math.pi / 6, 64)
    sv = fwd(star, 0, FE.star_features(sr, sp))
    vec = dict(meta=dict(r=rs.tolist(), out=mv.reshape(len(rs), -1).tolist()),
               ghost=dict(g=gi.tolist(), r=gr.tolist(), qa=ga.tolist(), qc=gc.tolist(), out=gv.tolist()),
               star=dict(r=sr.tolist(), phi=sp.tolist(), out=sv.tolist()))
    with open(os.path.join(OUT, 'flare-test-vectors.json'), 'w') as f:
        json.dump(vec, f)
    print('wrote', os.path.join(OUT, 'flare-weights.js'), '%.1f kB' % (len(js) / 1024))


if __name__ == '__main__':
    main()
