// Transliterates the scalar-GLSL world function (src/terrain/height.glsl.js) into plain JS: src/terrain/height.gen.js.
//   node src/terrain/tools/gen-height.mjs            write the file
//   import { generate } from './gen-height.mjs'      (used by the unit test to check the committed file is current)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { GLOBAL_NAMES, HASH_JS, WORLD_GLSL, airportsCode } from '../height.glsl.js';
import { AIRPORTS } from '../../data/airports.js';

export function glslToJs(src) {
  return src
    .replace(/\b(?:float|void|int)\s+(\w+)\s*\(([^)]*)\)\s*\{/g, (m, name, params) =>
      `function ${name}(${params.split(',').map((p) => p.trim().split(/\s+/).pop()).filter(Boolean).join(', ')}) {`)
    .replace(/\bfloat\s*\(/g, '(')
    .replace(/\b(?:float|int)\s+/g, 'let ');
}

export function generate() {
  const body = glslToJs(WORLD_GLSL.replace('//@AIRPORTS@', airportsCode(AIRPORTS)));
  return `// GENERATED by src/terrain/tools/gen-height.mjs from src/terrain/height.glsl.js — DO NOT EDIT.
/* eslint-disable */
const sin = Math.sin, cos = Math.cos, exp = Math.exp, sqrt = Math.sqrt, abs = Math.abs, floor = Math.floor, min = Math.min, max = Math.max;
function clamp(x, a, b) { return x < a ? a : x > b ? b : x; }
function mix(a, b, t) { return a * (1 - t) + b * t; }
let ${GLOBAL_NAMES.map((n) => n + ' = 0').join(', ')};
${HASH_JS}${body}
/** Terrain elevation, metres MSL (negative = seabed), at world x (east), z (south) in metres. */
export function heightAt(x, z) { return terrain(x, z); }
/** Height plus the generator's material outputs. out = { height, arid, special } */
export function sampleTerrain(x, z, out) { out.height = terrain(x, z); out.arid = Math.min(gArid, 1); out.dune = Math.max(gArid - 1, 0); out.special = gSpec; return out; }
/** Height as generated for a clipmap level with texel spacing \`lod\` metres (band-limited). Tools/tests only. */
export function heightAtLod(x, z, lod) { gLod = lod; const h = terrain(x, z); gLod = 0; return h; }
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = resolve(dirname(fileURLToPath(import.meta.url)), '../height.gen.js');
  writeFileSync(out, generate());
  console.log('wrote', out);
}
