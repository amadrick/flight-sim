import * as THREE from 'three';
import { createSandbox } from './sandbox.mjs';
import { createFlightController, profileOf } from '../fly.js';
import { headingVec } from '../../util.js';
const id = process.argv[2] || 'f15';
const b = await createSandbox({ seed: 1 });
const e = b.combat.world.spawnAircraft({ aircraft: id, team: 'red', position: new THREE.Vector3(0, 4500, 0), heading: 0, speed: 220 });
const prof = profileOf(e.def, e.sim); console.log(prof);
const fc = createFlightController(e, prof); const dir = new THREE.Vector3();
const T0 = +process.argv[3] || 0, T1 = +process.argv[4] || 12;
e.pilot = { update(dt) { headingVec(90, dir); fc.steer(dir, 7, 2.5); fc.speed(prof.corner); fc.apply(dt); } };
b.run(T1, (t) => { const s = e.state, c = e.controls; if (t >= T0 && Math.abs((t * 10) % 2.5) < 0.17) console.log(`t=${t.toFixed(2)} hdg ${(s.heading*57.3).toFixed(0)} pitch ${(s.pitch*57.3).toFixed(0)} roll ${(s.roll*57.3).toFixed(0)} g ${s.gLoad.toFixed(2)} cmd ${fc.nzCmd.toFixed(2)} re ${(fc.rollErr*57.3).toFixed(0)} ias ${s.ias.toFixed(0)} aoa ${(s.aoa*57.3).toFixed(1)} st ${c.pitch.toFixed(2)} rl ${c.roll.toFixed(2)} p ${(s.bodyRates.p*57.3).toFixed(0)} integ ${fc.integ.toFixed(2)} thr ${c.throttle.toFixed(2)}`); });
