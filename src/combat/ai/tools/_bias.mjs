import * as THREE from 'three';
import { createSandbox } from './sandbox.mjs';
import { createFlightController, profileOf } from '../fly.js';
const tg = +(process.argv[2] || 3);
const b = await createSandbox({ seed: 1 });
const w = b.combat.world;
const T = w.spawnAircraft({ aircraft: 'f16', team: 'red', position: new THREE.Vector3(0, 5000, 0), heading: 0, speed: 210, loadout: { ir: 0, radar: 0, hp: 1e6 } });
const fc = createFlightController(T, profileOf(T.def, T.sim));
T.pilot = { mode: 'target', update(dt) { fc.direct(tg, Math.acos(1 / tg), 9); fc.speed(180); fc.apply(dt); } };
const A = w.spawnAircraft({ aircraft: 'f16', team: 'blue', position: new THREE.Vector3(0, 5000, 600), heading: 0, speed: 220, skill: 0.9, loadout: { ir: 0, radar: 0 }, order: { type: 'cruise', heading: 0, alt: 5000, weaponsHold: true } });
A.pilot.tuning.aimSigma = 0;
let sx = 0, sy = 0, n = 0, k = 0;
globalThis.__AIDBG = (e, d) => { if (e !== A || b.combat.clock < 10) return; sx += d.ex; sy += d.ey; n++; if (k++ % 30 == 0) console.log(`t ${b.combat.clock.toFixed(1)} r ${d.r.toFixed(0)} ex ${(d.ex*1000).toFixed(0)} ey ${(d.ey*1000).toFixed(0)} g ${A.state.gLoad.toFixed(1)} ias ${A.state.ias.toFixed(0)} aoa ${(A.state.aoa*57.3).toFixed(1)} beta ${(A.state.beta*57.3).toFixed(1)}`); };
let en = false; b.run(30, (t) => { if (!en && t > 3) { en = true; A.pilot.setOrder({ type: 'engage', target: T }); } });
console.log('mean ex', (sx / n * 1000).toFixed(1), 'ey', (sy / n * 1000).toFixed(1));
